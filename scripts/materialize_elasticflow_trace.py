#!/usr/bin/env python3
import csv, json, math
from pathlib import Path

ANCHOR=0.6260788463455607
RAW=Path("audit/raw")
EXP=Path("audit/exp")
OUT=Path("data/elasticflow_cluster08_single_gpu.csv")
CFG=Path("configs/trace_elasticflow_itp.json")

def load(root,name):
    p=next(root.rglob(name))
    with p.open(newline="",encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))

raw=load(RAW,"cluster08.csv")
exp=load(EXP,"cluster08.csv")
exp_map={r["job_id"]:r for r in exp}

rows=[]
for r in raw:
    if float(r["num_gpu"])!=1 or float(r["duration"])<=0:
        continue
    e=exp_map.get(r["job_id"])
    if e is None:
        continue
    submission=float(r["submission_time"])
    duration=float(r["duration"])
    deadline=float(e["deadline"])
    slack=deadline-submission
    if slack<=0:
        continue
    rows.append({
        "job_id":r["job_id"],
        "submission_time":r["submission_time"],
        "duration":r["duration"],
        "num_gpu":r["num_gpu"],
        "deadline":e["deadline"],
        "num_iteration":e.get("num_iteration",""),
        "model_name":e.get("model_name",""),
        "batch_size":e.get("batch_size",""),
        "deadline_slack_ratio":f"{slack/duration:.12g}",
    })
rows.sort(key=lambda r:(float(r["submission_time"]),r["job_id"]))
if len(rows)!=12558:
    raise RuntimeError(f"Expected 12558 matched single-GPU jobs, got {len(rows)}")

ratios=sorted(float(r["deadline_slack_ratio"]) for r in rows)
def quantile_linear(values,q):
    n=len(values)
    pos=(n-1)*q
    lo=math.floor(pos); hi=math.ceil(pos)
    if lo==hi: return values[lo]
    w=pos-lo
    return values[lo]*(1-w)+values[hi]*w
q33=quantile_linear(ratios,.33)
q67=quantile_linear(ratios,.67)

OUT.parent.mkdir(parents=True,exist_ok=True)
with OUT.open("w",newline="",encoding="utf-8") as f:
    fields=list(rows[0])
    w=csv.DictWriter(f,fieldnames=fields); w.writeheader(); w.writerows(rows)

windows={}
for m in (32,64,128):
    st=math.floor(ANCHOR*(len(rows)-m))
    en=st+m-1
    block=rows[st:en+1]
    windows[str(m)]={
        "start_index":st,"end_index":en,
        "first_task":block[0]["job_id"],"last_task":block[-1]["job_id"],
        "submission_span_hours":(float(block[-1]["submission_time"])-float(block[0]["submission_time"]))/3600.0,
    }

cfg={
    "dataset_id":"microsoft_elasticflow_itp_cluster08",
    "status":"locked-pre-results",
    "source":{
        "repository":"microsoft/elasticflow-traces",
        "ref":"main",
        "raw_archive_path":"data/raw-traces.tar.gz",
        "raw_archive_blob_sha":"8147e243486d25a21abb12c1e50cbcf90aa72ebc",
        "raw_archive_sha256":"67398e1a89245c50ae0881bf997e6cda0c95f9f47980af5bc56d67998965669f",
        "experiment_archive_path":"data/elasticflow-traces.tar.gz",
        "experiment_archive_blob_sha":"bf9e3ccae14b35410a213b2528c02e71906f8890",
        "experiment_archive_sha256":"e9c20b73de61d2702aef086aebc995cbc432affbd0f09969cf30879c5d1a83c4",
        "cluster_file":"cluster08.csv"
    },
    "selection":{
        "cluster_rule":"cluster with largest count of positive-duration single-GPU raw jobs",
        "eligible_rule":"raw num_gpu==1 and duration>0, exact job_id match in authors' experiment trace, positive generated deadline slack",
        "eligible_count":len(rows),
        "sampling_method":"contiguous block from submission-time-sorted eligible pool",
        "anchor_fraction":ANCHOR,
        "primary_size":64,
        "scalability_sizes":[32,64,128],
        "windows":windows
    },
    "deadline":{
        "source":"matching ElasticFlow experiment trace deadline field",
        "description":"deadline is generated by the ElasticFlow authors based on their experiment rules; it is not a raw production field",
        "slack_ratio_tertiles":{"q33":q33,"q67":q67},
        "carbon_class_rule":"critical if slack_ratio<=q33, deferred if q33<ratio<=q67, flexible otherwise"
    },
    "workload_mapping":{
        "gpu_demand":1.0,
        "cpu_demand":0.0,
        "memory_demand":0.0,
        "bandwidth_demand":0.0,
        "arrival_time":"submission_time relative to first job in selected window",
        "observed_runtime":"duration / 3600",
        "deadline":"(source deadline - first selected submission_time) / 3600"
    },
    "service_time":{
        "primary_rule":"observed raw duration / locked FP32 resource speed factor",
        "reference_hardware":"RTX A6000 normalized speed factor 1.0",
        "limitation":"source hardware is not identified per job; treating raw duration as A6000-equivalent is a reconstruction proxy"
    },
    "qpeo_features":{
        "performance_affinity":"row-wise normalized inverse service time",
        "thermal_headroom":"1 - resource_max_power / max_resource_max_power",
        "dependency_matrix":"all zeros because the trace does not expose job dependency metadata"
    }
}
CFG.parent.mkdir(parents=True,exist_ok=True)
CFG.write_text(json.dumps(cfg,indent=2)+"\n",encoding="utf-8")
print(json.dumps(cfg["selection"],indent=2))
print("deadline tertiles",q33,q67)
